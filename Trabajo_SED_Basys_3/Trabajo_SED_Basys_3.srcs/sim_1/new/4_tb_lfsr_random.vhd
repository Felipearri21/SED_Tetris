library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity tb_lfsr_random is
end entity;

architecture TB of tb_lfsr_random is

    -------------------------------------------------------------------------
    -- Señales del DUT
    -------------------------------------------------------------------------
    signal clk        : std_logic := '0';
    signal reset      : std_logic := '0';
    signal random_out : integer;

    -------------------------------------------------------------------------
    -- Parámetros de simulación
    -------------------------------------------------------------------------
    constant CLK_PERIOD : time := 10 ns;

begin

    -------------------------------------------------------------------------
    -- Generación de reloj
    -------------------------------------------------------------------------
    clk <= not clk after CLK_PERIOD/2;

    -------------------------------------------------------------------------
    -- Instancia del DUT
    -------------------------------------------------------------------------
    dut : entity work.lfsr_random
        port map (
            clk        => clk,
            reset      => reset,
            random_out => random_out
        );

    -------------------------------------------------------------------------
    -- Proceso de estímulos
    -------------------------------------------------------------------------
    stim_proc : process
    begin
        ---------------------------------------------------------------------
        -- Reset inicial
        ---------------------------------------------------------------------
        reset <= '1';
        wait for 30 ns;
        reset <= '0';

        ---------------------------------------------------------------------
        -- Observar secuencia durante varios ciclos
        ---------------------------------------------------------------------
        wait for 300 ns;

        ---------------------------------------------------------------------
        -- Forzar nuevo reset y comprobar repetibilidad
        ---------------------------------------------------------------------
        reset <= '1';
        wait for 30 ns;
        reset <= '0';

        wait for 200 ns;

        ---------------------------------------------------------------------
        -- Fin de simulación
        ---------------------------------------------------------------------
        wait;
    end process;

end architecture;
