library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity tb_clk_divider is
end entity;

architecture TB of tb_clk_divider is

    -------------------------------------------------------------------------
    -- Señales del DUT
    -------------------------------------------------------------------------
    signal clk       : std_logic := '0';
    signal reset     : std_logic := '0';
    signal level     : integer   := 1;
    signal tick_game : std_logic;
    signal tick_drop : std_logic;

    -------------------------------------------------------------------------
    -- Parámetros de simulación (valores pequeños)
    -------------------------------------------------------------------------
    constant CLK_PERIOD : time := 10 ns;

begin

    -------------------------------------------------------------------------
    -- Generación de reloj
    -------------------------------------------------------------------------
    clk <= not clk after CLK_PERIOD/2;

    -------------------------------------------------------------------------
    -- Instancia del DUT
    -------------------------------------------------------------------------
    dut : entity work.clk_divider
        generic map (
            GAME_SPEED => 10,   -- ticks rápidos para simulación
            DROP_BASE  => 30,
            DROP_STEP  => 5,
            DROP_MIN   => 10
        )
        port map (
            clk       => clk,
            reset     => reset,
            level     => level,
            tick_game => tick_game,
            tick_drop => tick_drop
        );

    -------------------------------------------------------------------------
    -- Proceso de estímulos
    -------------------------------------------------------------------------
    stim_proc : process
    begin
        ---------------------------------------------------------------------
        -- Reset inicial
        ---------------------------------------------------------------------
        reset <= '1';
        wait for 50 ns;
        reset <= '0';

        ---------------------------------------------------------------------
        -- Nivel 1
        ---------------------------------------------------------------------
        level <= 1;
        wait for 300 ns;

        ---------------------------------------------------------------------
        -- Nivel 3 (drop más rápido)
        ---------------------------------------------------------------------
        level <= 3;
        wait for 300 ns;

        ---------------------------------------------------------------------
        -- Nivel alto (saturación por DROP_MIN)
        ---------------------------------------------------------------------
        level <= 10;
        wait for 300 ns;

        ---------------------------------------------------------------------
        -- Fin de simulación
        ---------------------------------------------------------------------
        wait;
    end process;

end architecture;
