library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity tb_seven_seg_driver is
end entity;

architecture TB of tb_seven_seg_driver is

    -------------------------------------------------------------------------
    -- Señales
    -------------------------------------------------------------------------
    signal clk   : std_logic := '0';
    signal value : integer range 0 to 9999 := 0;
    signal seg   : std_logic_vector(6 downto 0);
    signal an    : std_logic_vector(3 downto 0);

    constant CLK_PERIOD : time := 10 ns;

begin

    -------------------------------------------------------------------------
    -- Clock
    -------------------------------------------------------------------------
    clk <= not clk after CLK_PERIOD/2;

    -------------------------------------------------------------------------
    -- DUT
    -------------------------------------------------------------------------
    dut : entity work.seven_seg_driver
        port map (
            clk   => clk,
            value => value,
            seg   => seg,
            an    => an
        );

    -------------------------------------------------------------------------
    -- Estímulos
    -------------------------------------------------------------------------
    stim_proc : process
    begin
        ---------------------------------------------------------------------
        -- Mostrar 1234
        ---------------------------------------------------------------------
        value <= 1234;
        wait for 1 ms;

        ---------------------------------------------------------------------
        -- Mostrar 0007
        ---------------------------------------------------------------------
        value <= 7;
        wait for 1 ms;

        ---------------------------------------------------------------------
        -- Mostrar 9999
        ---------------------------------------------------------------------
        value <= 9999;
        wait for 1 ms;

        ---------------------------------------------------------------------
        -- FIN
        ---------------------------------------------------------------------
        wait;
    end process;

end architecture;
